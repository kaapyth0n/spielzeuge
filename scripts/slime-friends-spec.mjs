import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 const page=await browser.newPage({viewport:{width:1280,height:1000}}), errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 const action=id=>page.locator(`[data-action="${id}"]`).click()
 const room=id=>page.locator(`nav [data-room="${id}"]`).click()
 const read=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('spielzeuge.slime-check.v1')))
 await page.goto('http://localhost:5173/slime-check/')
 await action('hold'); await room('outside')
 assert.equal(await page.locator('[data-action="play-friend"]').count(),0)
 await action('ask-owner'); await action('ask-slimes')
 assert.match(await page.locator('.wishes').innerText(),/сначала подружимся/)
 for(let i=0;i<3;i++) await action('play-friend')
 assert.equal((await read()).friendship,3)
 await action('ask-slimes'); await action('give-piece'); assert.equal((await read()).baby,null)
 await action('later'); assert.equal((await read()).baby,null)
 await action('ask-slimes'); await action('give-piece'); await action('give-piece')
 assert.equal((await read()).baby.color,'mint'); assert.equal(await page.locator('.baby-slime').count(),1)
 await action('cuddle'); assert.equal((await read()).baby.cuddles,1)
 await page.screenshot({path:'tmp/slime-friends-desktop.png',fullPage:true})
 await room('home'); assert.equal(await page.locator('.baby-slime').count(),1)
 await page.reload(); assert.equal((await read()).baby.cuddles,1); assert.equal(await page.locator('.baby-slime').count(),1)
 await page.setViewportSize({width:390,height:844}); await action('hold'); await room('outside')
 assert.equal(await page.locator('[data-action="play-friend"]').count(),0)
 await action('ask-owner'); assert.equal(await page.locator('[data-action="give-piece"]').count(),0)
 await page.screenshot({path:'tmp/slime-friends-phone.png',fullPage:true})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
 // Dirty slime is asked to bathe before playing, then can return.
 await page.locator('#slime').scrollIntoViewIfNeeded()
 const slime=await page.locator('#slime').boundingBox(), scene=await page.locator('#scene').boundingBox()
 await page.mouse.move(slime.x+slime.width/2,slime.y+slime.height/2); await page.mouse.down(); await page.mouse.move(scene.x+scene.width/2,scene.y+scene.height*.93,{steps:10}); await page.mouse.up()
 await room('home'); await action('hold'); await room('outside'); await action('ask-owner')
 assert.equal(await page.locator('[data-action="play-friend"]').count(),0)
 assert.match(await page.locator('.speech').innerText(),/смойте грязь/)
 assert.deepEqual(errors,[])
 console.log('PASS: permission, friendship, both wishes, cancel, two pieces, baby, cuddle, save, repeat visit, refusal, mobile; no JS errors')
} finally { await browser.close() }
